const cache = new Map<string, string>();

/** Inline SVG for a pixel icon. Decorative by default (aria-hidden). */
export function icon(name: PixelIconName, cls = 'pi'): string {
    const key = `${name}|${cls}`;
    const hit = cache.get(key);
    if (hit) return hit;
    let d = '';
    G[name].forEach((row, y) => {
        for (let x = 0; x < row.length;) {
            if (row[x] !== '#') { x++; continue; }
            let w = 0;
            while (row[x + w] === '#') w++;
            d += `M${x} ${y}h${w}v1h-${w}z`;
            x += w;
        }
    });
    const svg = `<svg class="${cls}" viewBox="0 0 12 12" width="12" height="12" aria-hidden="true" focusable="false" shape-rendering="crispEdges"><path fill="currentColor" d="${d}"/></svg>`;
    cache.set(key, svg);
    return svg;
}
